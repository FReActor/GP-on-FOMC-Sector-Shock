"""Export every evolved GP formula, with its train and test score, to formulas/.

    python -m src.export_formulas

Reads results/*_seeds.csv (one row per GP run: ticker, horizon, seed, formula, test r2_oos) and
results/preds/*.csv (per-event predictions, to compute the in-sample score). Writes:

    formulas/gp_formulas.csv        one row per run, all models: plain-text and LaTeX formula, scores
    formulas/GP1_surprise_only.md   GP1 (gp_v0): input is surprise_bp only
    formulas/GP2_features.md        GP2 (gp_v1): surprise_bp + vix, slope_2s10s, beta_1y, mom_20d

r2_train is on train+val (the years GP was fit and tuned on), r2_test is r2_oos on the test years.
Both use the per-ticker train mean as the benchmark, same as src/data.r2_oos.
Nothing is re-run: the script only reads saved results, so it is deterministic.
"""

import pandas as pd
import sympy as sp

from src import config
from src.data import r2_oos

OUT = config.ROOT / "formulas"
FULL_TRAIN = ["train", "val"]
SYMBOLS = {f: sp.Symbol(f) for f in config.FEATURES}  # so names like beta_1y stay plain symbols

# (model, scope, seeds file, preds file)
RUNS = [
    ("GP1", "pooled", "gp_v0_seeds.csv", "gp_v0.csv"),
    ("GP1", "per-ticker", "gp_v0_seeds.csv", "gp_v0_ticker.csv"),
    ("GP2", "pooled", "gp_v1_pooled_seeds.csv", "gp_v1_pooled.csv"),
    ("GP2", "per-ticker", "gp_v1_per_ticker_seeds.csv", "gp_v1_per_ticker.csv"),
]
TITLES = {"GP1": ("GP1_surprise_only.md", "GP1: surprise only (`gp_v0`)", "surprise_bp"),
          "GP2": ("GP2_features.md", "GP2: surprise + features (`gp_v1`)",
                  "surprise_bp, vix, slope_2s10s, beta_1y, mom_20d")}


def load() -> pd.DataFrame:
    frames = []
    for model, scope, seeds_file, preds_file in RUNS:
        s = pd.read_csv(config.RESULTS / seeds_file)
        s = s[(s["ticker"] == "POOLED") == (scope == "pooled")].copy()
        p = pd.read_csv(config.RESULTS / "preds" / preds_file)
        tr = p[p["split"].isin(FULL_TRAIN)]
        tr = tr.join(tr.groupby(["ticker", "horizon"])["y"].mean().rename("ybar"), on=["ticker", "horizon"])
        if scope == "pooled":
            tr = tr.assign(ticker="POOLED")
        g = tr.groupby(["ticker", "horizon", "seed"])
        r2 = (g.apply(lambda x: r2_oos(x["y"], x["yhat"], x["ybar"].to_numpy()), include_groups=False)
               .rename("r2_train").to_frame()
               # constant = the run predicts one number for every event (judged on the predictions,
               # not the sympy string: protected division can make a "0" formula non-constant)
               .join((g["yhat"].std() < 1e-12).rename("constant")).reset_index())
        s = s.merge(r2, on=["ticker", "horizon", "seed"], how="left")
        frames.append(s.assign(model=model, scope=scope))
    d = pd.concat(frames, ignore_index=True).rename(columns={"r2_oos": "r2_test"})
    d["formula"] = d["formula"].astype(str)
    d["latex"] = d["formula"].map(to_latex)
    cols = ["model", "scope", "ticker", "horizon", "seed", "parsimony", "length", "constant",
            "r2_train", "r2_test", "hit_rate", "n_train", "n_test", "formula", "latex", "program"]
    return d[cols].sort_values(["model", "scope", "ticker", "horizon", "seed"]).reset_index(drop=True)


def to_latex(formula: str) -> str:
    """sympy string -> LaTeX. Pipes are swapped for \\lvert/\\rvert so markdown tables don't break."""
    names = SYMBOLS
    pretty = {s: r"\mathrm{" + n.replace("_", r"\_") + "}" for n, s in names.items()}
    tex = sp.latex(sp.sympify(formula, locals=names), min=-3, max=3, symbol_names=pretty)
    tex = tex.replace(r"\left|", r"\left\lvert ").replace(r"\right|", r"\right\rvert ")
    return tex.replace("|", r"\vert ")


def md_model(d: pd.DataFrame, model: str) -> str:
    fname, title, inputs = TITLES[model]
    out = [f"# {title}", "",
           f"Inputs: {inputs}. Generated by `python -m src.export_formulas`; do not edit by hand.", "",
           "One row per GP run (10 seeds per cell). The formula predicts the sector's excess return over "
           "SPY, in percent. `R² train` is on 1999-2009 (train+val), `R² test` is out of sample on "
           "2010-2015; both against the per-ticker train mean. *const* = the run predicts the same number "
           "for every event.", "",
           "Reading caveat: gplearn's `div` is protected (returns 1 when the denominator is near 0) and "
           r"surprise_bp is exactly 0 on ~9% of events, so a term like $c/\mathrm{surprise\_bp}$ is "
           "really a switch on 'no surprise'. sympy prints plain $a/b$ and can even simplify such a "
           "program to $0$; the raw gplearn program is in `gp_formulas.csv` (column `program`).", ""]
    for scope in ("pooled", "per-ticker"):
        s = d[(d["model"] == model) & (d["scope"] == scope)]
        out += [f"## {scope.capitalize()}", ""]
        for (t, h), g in s.groupby(["ticker", "horizon"], sort=True):
            med = g["r2_test"].median()
            out += [f"### {t}, {h}  (median R² test {med:+.3f})", "",
                    "| seed | parsimony | length | R² train | R² test | formula |",
                    "|---:|---:|---:|---:|---:|---|"]
            for r in g.itertuples():
                tag = " *const*" if r.constant else ""
                out.append(f"| {r.seed} | {r.parsimony:g} | {r.length} | {r.r2_train:+.3f} | "
                           f"{r.r2_test:+.3f} | ${r.latex}${tag} |")
            out.append("")
    return "\n".join(out)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    d = load()
    d.to_csv(OUT / "gp_formulas.csv", index=False)
    for model, (fname, _, _) in TITLES.items():
        (OUT / fname).write_text(md_model(d, model), encoding="utf-8")
    s = (d.groupby(["model", "scope", "horizon"])
          .agg(runs=("seed", "size"), constant=("constant", "mean"), med_length=("length", "median"),
               med_r2_train=("r2_train", "median"), med_r2_test=("r2_test", "median")).reset_index())
    rows = ["| model | scope | horizon | runs | constant | median length | median R² train | median R² test |",
            "|---|---|---|---:|---:|---:|---:|---:|"]
    rows += [f"| {r.model} | {r.scope} | {r.horizon} | {r.runs} | {r.constant:.0%} | {r.med_length:g} | "
             f"{r.med_r2_train:+.3f} | {r.med_r2_test:+.3f} |" for r in s.itertuples()]
    index = ["# GP formulas", "",
             "Every formula the GP evolved in Stage 1, one row per run (model x scope x ticker x horizon "
             "x seed). Generated from `results/` by `python -m src.export_formulas`; do not edit by hand.", "",
             "- [GP1_surprise_only.md](GP1_surprise_only.md): GP1, input `surprise_bp` only",
             "- [GP2_features.md](GP2_features.md): GP2, `surprise_bp` + `vix`, `slope_2s10s`, `beta_1y`, `mom_20d`",
             "- [gp_formulas.csv](gp_formulas.csv): all runs, with the raw gplearn `program`, the sympy "
             "`formula`, its `latex`, `r2_train` (1999-2009), `r2_test` (2010-2015), `hit_rate`", "",
             "Pooled = one formula for all sectors; per-ticker = one per sector ETF. 10 seeds per cell; "
             "parsimony picked per run on the 2007-2009 validation years.", "", *rows, ""]
    (OUT / "README.md").write_text("\n".join(index), encoding="utf-8")
    print(f"{len(d)} formulas -> {OUT}")
    print(s.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
